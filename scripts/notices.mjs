// Generates THIRD_PARTY_NOTICES.md from the license files of everything bundled into the app.
// Run after changing dependencies: node scripts/notices.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const nm = (p) => join(root, 'node_modules', p)
const pkg = (name) => JSON.parse(readFileSync(nm(`${name}/package.json`), 'utf8'))
const lock = JSON.parse(readFileSync(join(root, 'assets.lock.json'), 'utf8'))
// MediaPipe's npm package declares Apache-2.0 but ships no license file; the license text is the
// standard Apache License 2.0, taken here from another Apache-2.0 package's copy.
const APACHE = readFileSync(nm('typescript/LICENSE.txt'), 'utf8').replace(/\r\n/g, '\n')

const bundled = [
  { name: 'electron', use: 'Desktop runtime (Chromium and Node.js; Chromium notices ship as LICENSES.chromium.html)', file: 'LICENSE' },
  { name: '@mediapipe/tasks-vision', use: 'Pose Landmarker runtime (WebAssembly), bundled', text: APACHE },
  { name: 'react', use: 'User interface', file: 'LICENSE' },
  { name: 'react-dom', use: 'User interface', file: 'LICENSE' },
  { name: 'scheduler', use: 'User interface (React dependency)', file: 'LICENSE' },
  { name: 'zustand', use: 'User interface state', file: 'LICENSE' },
  { name: 'zod', use: 'Input validation in the main process', file: 'LICENSE' },
  { name: '@fontsource-variable/anybody', use: 'Display typeface (Anybody)', file: 'LICENSE' },
  { name: '@fontsource-variable/instrument-sans', use: 'Interface typeface (Instrument Sans)', file: 'LICENSE' },
  { name: '@fontsource/ibm-plex-mono', use: 'Diagnostics typeface (IBM Plex Mono)', file: 'LICENSE' }
]

let md = `# Third-party notices

Ready Up includes the following third-party software and data. Full license texts follow the table.
This file is generated by \`scripts/notices.mjs\`.

| Component | Version | License | Used for |
|---|---|---|---|
`
for (const b of bundled) {
  const p = pkg(b.name)
  md += `| ${b.name} | ${p.version} | ${p.license} | ${b.use} |\n`
}
for (const f of lock.files.filter((f) => f.from === 'url')) {
  md += `| ${f.path.split('/').pop()} | pinned, sha256 ${f.sha256.slice(0, 12)}… | ${f.license} | Pose model, bundled. Source: ${f.source} |\n`
}

md += `
## Acknowledgement (reference only, no code used)

The push-up counter was designed after evaluating
[parhamsoltani/pushup_counter](https://github.com/parhamsoltani/pushup_counter)
(MIT License, Copyright (c) 2025 parhamsoltani). Ready Up's counter is an independent TypeScript
implementation; no code from that project is included. Its sample video and image are not used or
redistributed.

## Pose model

The Pose Landmarker models are based on Google's BlazePose GHUM 3D model, licensed under the
Apache License, Version 2.0, per its model card. The model card lists out-of-scope uses including
tracking multiple people, people farther than about 4 m from the camera, and any form of
surveillance or identity recognition.

## License texts
`
for (const b of bundled) {
  const p = pkg(b.name)
  const text = (b.text ?? readFileSync(nm(`${b.name}/${b.file}`), 'utf8')).replace(/\r\n/g, '\n')
  md += `\n### ${b.name} ${p.version} (${p.license})\n\n\`\`\`\n${text.trim()}\n\`\`\`\n`
}
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), md)
console.log(`Wrote THIRD_PARTY_NOTICES.md (${bundled.length} packages, ${md.length} bytes)`)
